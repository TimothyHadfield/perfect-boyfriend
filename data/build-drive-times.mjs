// Builds data/drive-times.json: real road drive times between every plan stop (and the Orem start).
// Run: node data/build-drive-times.mjs   (after build-plan-stops.mjs; needs internet)
// Source: the free OSRM public demo server (router.project-osrm.org, OpenStreetMap roads, no traffic).
// Polite: chunks of 40 points per side (<= 80 coordinates per request), one request per ~1.1 s, retries with backoff.
// Output: { ids: [...], min: [[...]] } where min[i][j] = whole driving minutes from ids[i] to ids[j]
// (no parking; js/logic/plan.js adds its parking minutes). "orem" = the Orem start point (OREM in plan.js).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const { stops } = JSON.parse(readFileSync(join(here, 'plan-stops.json'), 'utf8'));
const OREM = { id: 'orem', lat: 40.2969, lng: -111.6946 };     // keep in step with OREM in js/logic/plan.js
const pts = [OREM, ...stops.filter((s) => !s.home && s.lat != null && s.lng != null)];
const CHUNK = 40;
const BASE = 'https://router.project-osrm.org/table/v1/driving/';
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function table(src, dst) {
  const all = [...src, ...dst];
  const coords = all.map((p) => `${p.lng.toFixed(5)},${p.lat.toFixed(5)}`).join(';');
  const s = src.map((_, i) => i).join(';');
  const d = dst.map((_, i) => i + src.length).join(';');
  const url = `${BASE}${coords}?sources=${s}&destinations=${d}&annotations=duration`;
  for (let attempt = 1; attempt <= 6; attempt++) {
    try {
      const res = await fetch(url, { headers: { 'User-Agent': 'perfect-boyfriend-plan-builder (personal, one-off)' } });
      if (res.ok) {
        const j = await res.json();
        if (j.code === 'Ok') return j.durations;
        throw new Error('OSRM ' + j.code + ' ' + (j.message || ''));
      }
      throw new Error('HTTP ' + res.status);
    } catch (err) {
      const wait = 1500 * 2 ** (attempt - 1);
      console.warn(`  retry ${attempt} in ${wait} ms: ${err.message}`);
      await sleep(wait);
    }
  }
  throw new Error('OSRM kept failing; try again later');
}

const n = pts.length;
const min = Array.from({ length: n }, () => Array(n).fill(null));
const chunks = [];
for (let i = 0; i < n; i += CHUNK) chunks.push([i, Math.min(n, i + CHUNK)]);
let reqs = 0;
for (const [a0, a1] of chunks) {
  for (const [b0, b1] of chunks) {
    if (reqs++) await sleep(1100);
    const dur = await table(pts.slice(a0, a1), pts.slice(b0, b1));
    for (let i = a0; i < a1; i++) for (let j = b0; j < b1; j++) {
      const sec = dur[i - a0][j - b0];
      min[i][j] = sec == null ? null : Math.round(sec / 60);
    }
    console.log(`request ${reqs}/${chunks.length ** 2} ok`);
  }
}
const missing = min.flat().filter((x) => x == null).length;
if (missing) console.warn(missing, 'pairs with no route (left null; the app estimates those)');

const body = JSON.stringify({
  built: new Date().toISOString().slice(0, 10),
  note: 'Generated by data/build-drive-times.mjs from the OSRM public server (OpenStreetMap roads, no traffic). min[i][j] = driving minutes from ids[i] to ids[j], parking not included. "orem" = the Orem start.',
  ids: pts.map((p) => p.id),
  min: [],
}).replace('"min":[]', '"min":[\n' + min.map((r) => JSON.stringify(r)).join(',\n') + '\n]');
writeFileSync(join(here, 'drive-times.json'), body);
console.log(n, 'points,', reqs, 'requests, wrote drive-times.json', (body.length / 1024).toFixed(1), 'KB');
